export function serviceOf(p) {
  const s = (p.service + ' ' + p.sector).toLowerCase();
  if (/ai|personalis|traceab/.test(s)) return 'ai';
  if (/squad|platform engineering|integrations|software/.test(s)) return 'sw';
  if (/app/.test(s)) return 'app';
  return 'web';
}

